export function respondInstruction(mode, { downgraded = false } = {}) {
  const note = downgraded
    ? 'ผู้ใช้ขอไพ่ดาบ แต่ระบบเห็นว่าตอนนี้เขาควรได้รับกำลังใจก่อน ให้ตอบเป็นไพ่ถ้วย และบอกสั้น ๆ ในประโยคแรกว่า “ตอนนี้ไพ่ถ้วยน่าจะตรงใจที่สุด ความจริงแรง ๆ ไว้ก่อนก็ได้” อย่าบอกเหตุผลเชิงเทคนิค'
    : '';
  return `ขั้นตอน: ตอบตามไพ่ที่ผู้ใช้เลือก ใช้ insightHypotheses และบทสนทนาทั้งหมด ยึดคำแก้ล่าสุดของผู้ใช้
${note}
${mode === 'swords' ? SWORDS_STEPS : CUPS_STEPS}`.trim();
}

export function followUpInstruction(mode) {
  return `ขั้นตอน: ผู้ใช้คุยต่อหลังได้ฟังไพ่${mode === 'swords' ? 'ดาบ' : 'ถ้วย'}ไปแล้ว
- ดูปฏิกิริยาของเขาก่อน ถ้าเขาเจ็บ รู้สึกแรงไป หรือเงียบลง ให้ซ่อมความรู้สึกก่อนและเปลี่ยนเป็นน้ำเสียงไพ่ถ้วย
- ถ้าเขารับได้และอยากไปต่อ ให้ต่อยอดไปที่การลงมือทำจากคำท้าที่ให้ไว้
- ถ้าเขาถามหรือแย้ง ตอบตรงประเด็นก่อน ไม่ย้อนเล่าทั้งก้อนซ้ำ และเปิดให้เขาไม่เห็นด้วยได้
- ตอบ 3-6 ประโยค ถามกลับได้ไม่เกินหนึ่งข้อ`;
}

