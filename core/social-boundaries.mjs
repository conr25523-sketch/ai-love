const clean = text => analyzeThaiText(typeof text === 'string' ? text.slice(0, 4000) : '').normalized;
const BLOCK = /ฆ่า|ทำร้าย|อยากตาย|ไม่อยากอยู่|อยากหายไป|ขิต|ตุย|กรีดแขน|ยาเกินขนาด|เลือดออก|(?:จะ|อยาก).{0,12}(?:ตบ|ต่อย|แทง)|วินิจฉัย|รักษา|คดี|ฟ้อง|แจ้งความ|ลงทุน|เงินกู้|เปลี่ยนเรื่อง|คุยเล่น|^(?:ไม่ใช่|ไม่ตรง|เข้าใจผิด|หยุด|พอแล้ว|ข้าม)/u;
const HESITATION = /^(?:เอ่อ|เออ|อ่า|อืม|อือ|หืม|หะ|งง)(?:นะ|อะ|อ่ะ|ครับ|ค่ะ)?[.!?\s]*$/u;

function mediation(text) {
  if (BLOCK.test(text) || /ไม่ได้เป็นคนกลาง|ไม่เคยเป็นคนกลาง|ไม่มีใคร(?:ให้|ฝาก|ใช้)/u.test(text)) return false;
  return /(?:เรา|ฉัน|ผม|กู|หนู).{0,16}(?:เป็น|รับบท|ทำหน้าที่).{0,8}คนกลาง|(?:ให้|ใช้|ฝาก|ดึง).{0,24}คนกลาง|ไม่อยากเป็นคนกลาง/u.test(text)
    || (/(?:เพื่อน|คนอื่น).{0,40}(?:ให้|ใช้|ฝาก).{0,24}(?:บอก|ถาม|คุย|ติดต่อ|ส่งข้อความ)/u.test(text)
      && /คุยกันเอง|อีกคน|คนนู้น|คนนั้น|คนนี้|(?:ถาม|บอก|กับ).{0,8}คนอื่น|แทน|ไปถาม/u.test(text));
}

function eventOf(text) {
  const current = text.replace(/ไม่(?:ได้|เคย)?(?:โยนงาน|ทิ้งงาน|บังคับ|จี้|กดดัน|ถามเรื่องส่วนตัว|พูดแทรก)/gu, '');
  if (mediation(current)) return 'mediation';
  if (/(?:งานกลุ่ม|งานทีม|โปรเจกต์|เพื่อนร่วมงาน|เพื่อน).{0,70}(?:โยนงาน|ทิ้งงาน|ไม่ช่วย|ให้เราทำ|ให้กูทำ|ทำคนเดียว|แบกคนเดียว)|(?:เรา|ฉัน|ผม|กู|หนู).{0,25}(?:ทำงานกลุ่ม|ทำงานทีม).{0,25}(?:คนเดียว|ไม่ช่วย)/u.test(current)) return 'workload';
  if (/(?:เพื่อน|คนอื่น|ที่บ้าน|ครอบครัว|พ่อ|แม่|เขา|มัน).{0,50}(?:บังคับ|จี้|กดดัน|ถามเรื่องส่วนตัว|ถามซ้ำ|ถามเซ้าซี้)|(?:บังคับ|จี้|กดดัน).{0,15}(?:เรา|ฉัน|กู|ผม|หนู)/u.test(current)
      && /ไม่อยาก|ไม่สะดวก|อึดอัด|รำคาญ|เดือด|หงุดหงิด|ไม่ชอบ|เบื่อ|เหนื่อย/u.test(current)) return 'pressure';
  if (/(?:เพื่อน|คนอื่น|เขา|มัน).{0,60}(?:ไม่ฟัง|พูดแทรก|ตัดบท|บอก(?:ว่า)?(?:เรา|กู|ฉัน)?คิดมาก)|(?:เล่า|พูด).{0,20}(?:ไม่ฟัง|ถูกตัดบท)/u.test(current)) return 'dismissal';
  return null;
}

