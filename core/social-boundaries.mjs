function recent(messages, role) {
  return Array.isArray(messages) ? messages.slice(-24).flatMap(message => {
    const content = message?.content ?? message?.text;
    return message?.role === role && typeof content === 'string' ? [clean(content)] : [];
  }) : [];
}

