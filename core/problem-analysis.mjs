import { analyzeThaiText } from './thai-language.mjs';
import { chooseReply } from './reply-variety.mjs';

// Multi-signal plans describe only stated conflicts. They are not a diagnosis,
// hidden motive, chain-of-thought transcript, or claim to model reasoning.
export function analyzeStatedProblem(text) {
  const current = analyzeThaiText(text).normalized;
  if (!current || /สมมติ|นิยาย|วินิจฉัย|รักษา|กินยา|ทำร้าย|อยากตาย|อยากหายไป/u.test(current)) return null;
  const facts = [];
  const add = (name, expression) => {
    const evidence = current.match(expression)?.[0];
    if (evidence) facts.push({ name, evidence });
    return !!evidence;
  };
  const subject = current.match(/คณิต|วิทย์|ภาษา|ศิลปะ|เขียนโปรแกรม/u)?.[0];
  // A newer explicit discovery/enjoyment detail gets the existing exploration
  // route instead of recycling the earlier ability/preference explanation.
  if (/สนุก.{0,25}ท้าทาย|ชอบ.{0,25}(?:ค้นพบ|เรียนรู้|ท้าทาย)|สนุก.{0,25}(?:รู้|ค้นพบ)/u.test(current)) return null;
  const subjects = new Set(current.match(/คณิต|วิทย์|ภาษา|ศิลปะ|เขียนโปรแกรม/gu) || []);
  if (subject && subjects.size === 1
      && !/ไม่(?:ได้|เคย|ค่อย)?(?:เก่ง|ถนัด)|(?:เพื่อน|เขา|น้อง|แฟน).{0,8}(?:เก่ง|ถนัด)/u.test(current)
      && add('ability', /เก่ง|ถนัด/u)
      && add('interest_conflict', /ไม่ได้ชอบ|ไม่ชอบ|ไม่สนุก|ไม่ได้อยากเรียน|ไม่อยากเรียน/u)) {
    return { kind: 'ability-interest', facts, subject,
      distinction: 'ความสามารถไม่เท่ากับความอยากทำต่อ',
      criterion: 'ความสนใจ ลักษณะงาน และต้นทุนการเรียน',
      review: 'เทียบประสบการณ์จริงมากกว่าคำชมเรื่องความเก่ง' };
  }
  facts.length = 0;
  if (!/ไม่(?:ได้|เคย|ค่อย)?(?:บังคับ|กดดัน|อยากให้|ให้เรียน)/u.test(current)
      && add('family_expectation', /(?:พ่อแม่|พ่อ|แม่|ที่บ้าน|ครอบครัว).{0,45}(?:บังคับ|กดดัน|อยากให้|ให้เรียน)/u)
      && add('study_choice', /เรียน|คณะ|สาย(?:วิทย์|ศิลป์)/u)
      && add('own_conflict', /แต่(?:เรา|ฉัน|ผม|หนู|กู)|ไม่อยาก|ไม่ชอบ|อึดอัด/u)) {
    return { kind: 'family-choice', facts,
      distinction: 'ความหวังดีของครอบครัวกับคนที่ต้องใช้ชีวิตบนทางเลือกนั้น',
      criterion: 'ค่าเรียน โอกาส และความรับผิดชอบต่อการเลือก',
      review: 'เสนอทางเลือกที่มีข้อมูลและขอบเขตความเสี่ยง' };
  }
  facts.length = 0;
  if (!/ไม่(?:ได้|เคย|ค่อย)?(?:กลัว|ต้องมีรายได้|ต้องใช้เงิน)|ไม่ได้มีงานเพิ่ม|งานไม่ได้เพิ่ม/u.test(current)
      && add('extra_work', /งาน(?:เพิ่ม|เยอะ)|(?:หัวหน้า|เจ้านาย).{0,25}(?:สั่ง|ให้).{0,12}(?:เพิ่ม|อีก)/u)
      && add('income_constraint', /กลัว.{0,20}(?:ตกงาน|เสียงาน|ไม่มีเงิน|เสียรายได้)|ต้องใช้เงิน|ต้องมีรายได้|ลาออกไม่ได้/u)) {
    return { kind: 'work-income', facts,
      distinction: 'ภาระที่เพิ่มขึ้นกับความจำเป็นต้องรักษารายได้',
      criterion: 'กำลัง เวลา และอำนาจต่อรองที่มีจริง',
      review: 'ดูผลของการจัดลำดับงานก่อนตัดสินใจเรื่องใหญ่' };
  }
  return null;
}

