import assert from 'node:assert/strict';
const base = new URL(process.env.MOONMIND_TEST_URL || 'http://127.0.0.1:5173');
assert.ok(['127.0.0.1', 'localhost'].includes(base.hostname));
const page = await fetch(new URL('/admin', base));
assert.equal(page.status, 200);
const html = await page.text();
assert.ok(html.includes('ประวัติการคุยของผู้ใช้'));
assert.ok(html.includes('/api/session') || html.includes('กำลังตรวจสิทธิ์'));
const home = await (await fetch(base)).text();
assert.ok(home.includes('href="/admin"'));
assert.equal((await fetch(new URL('/api/admin/users', base))).status, 401);
const signIn = await fetch(new URL('/signin-with-chatgpt?return_to=/admin', base), { redirect: 'manual' });
const cookie = signIn.headers.getSetCookie().map(value => value.split(';')[0]).join('; ');
assert.ok(cookie);
const session = await (await fetch(new URL('/api/session', base), { headers: { cookie } })).json();
assert.equal(session.isAdmin, true);
const users = await fetch(new URL('/api/admin/users', base), { headers: { cookie } });
assert.equal(users.status, 200);
assert.ok(Array.isArray((await users.json()).users));
console.log('Admin HTTP smoke passed: standalone route, entry links, authenticated administrator access, anonymous rejection. No chat profile required; no records modified.');
