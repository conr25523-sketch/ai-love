import assert from 'node:assert/strict';
const base = new URL(process.env.MOONMIND_TEST_URL || 'http://127.0.0.1:5173');
assert.ok(['127.0.0.1', 'localhost'].includes(base.hostname));
const path = '/api/admin/ai-settings';
const page = await fetch(new URL('/admin/settings', base));
assert.equal(page.status, 200);
assert.ok((await page.text()).includes('ตั้งค่า AI'));
assert.equal((await fetch(new URL(path, base))).status, 401);
const signin = await fetch(new URL('/signin-with-chatgpt?return_to=/admin/settings', base), { redirect: 'manual' });
const cookie = signin.headers.getSetCookie().map(value => value.split(';')[0]).join('; ');
assert.ok(cookie);
const status = await fetch(new URL(path, base), { headers: { cookie } });
assert.equal(status.status, 200);
assert.equal(status.headers.get('cache-control'), 'no-store');
const data = await status.json();
assert.equal(data.ready, true);
assert.deepEqual(Object.keys(data).sort(), ['configured', 'model', 'ready', 'updatedAt']);
const write = (origin, apiKey, withCookie = true) => fetch(new URL(path, base), { method: 'POST', headers: { ...(withCookie ? { cookie } : {}), origin, 'content-type': 'application/json' }, body: JSON.stringify({ apiKey, model: 'test-model' }) });
assert.equal((await write(base.origin, 'invalid', false)).status, 401);
assert.equal((await write('https://evil.test', 'invalid')).status, 403);
assert.equal((await write(base.origin, 'invalid')).status, 400);
console.log('Settings HTTP smoke passed: route, owner authentication, anonymous rejection, origin protection, bounded metadata. No external AI calls or database writes.');
